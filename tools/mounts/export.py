"""Voxel mount GLBs -> src/client/Mounts/Models/<look>.luau

  python tools/mounts/export.py [factor]

Each GLB (THREE.GLTFExporter) is a tree of pivot nodes ("body", "lFL" a
front leg's upper half, "lFL2" its lower half, "neck", "head", "wingL"...),
each placed by a matrix in its parent's space, with "<name>_mesh" (solid) and
"<name>_glow" (glowing) voxel shells in its own space. Out comes, per piece:
its parent, its pivot (in the parent's space) and its bricks merged into
boxes of one colour, `factor` GLB voxels to a brick (1 = every voxel; 2 or 3
for far fewer parts). Turned so the mount faces -Z like the rest (the GLBs
face +X): rig x = GLB z, rig z = -GLB x. Units: GLB voxels; the game scales
them so the body's top meets RideData.BackHeight (the rider's seat).
"""
import os, sys, math, json, struct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from vox import load_pieces, fill, downsample, boxes

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
OUT = os.path.join(ROOT, 'src', 'client', 'Mounts', 'Models')
DL = os.path.expanduser('~/Downloads')
FILES = {
    'seraph_steed': 'seraph-steed.glb',
    'nebula_kirin': 'nebula-kirin.glb',
    'bloomheart_stag': 'bloomheart-stag (1).glb',
}


def tree(path):
    f = open(path, 'rb').read()
    l = struct.unpack('<I', f[12:16])[0]
    j = json.loads(f[20:20 + l])
    nodes = j['nodes']
    parent = {}
    for i, n in enumerate(nodes):
        for c in n.get('children', []):
            parent[c] = i
    info = {}
    for i, n in enumerate(nodes):
        name = n.get('name') or ''
        if 'mesh' in n:
            continue
        m = n.get('matrix')
        t = (m[12], m[13], m[14]) if m else tuple(n.get('translation', (0, 0, 0)))
        p = parent.get(i)
        pname = nodes[p].get('name') if p is not None else None
        info[name] = {'pivot': t, 'parent': pname}
    return info


def rig(v):
    """GLB (x, y, z) -> rig (z, y, -x)"""
    return (v[2], v[1], -v[0])


def export(look, fname, factor):
    path = os.path.join(DL, fname)
    pieces = load_pieces(path)
    info = tree(path)
    root = [k for k, v in info.items() if v['parent'] is None][0]
    out_pieces = []
    palette, pidx = [], {}
    nparts = 0
    order = []
    # parents before children
    def walk(name):
        for k, v in info.items():
            if v['parent'] == name:
                order.append(k)
                walk(k)
    walk(root)
    back = None
    for name in order:
        cells = pieces.get(name, {})
        par = info[name]['parent']
        bx = []
        if cells:
            c = downsample(fill(cells), factor)
            for (x0, y0, z0, x1, y1, z1, col) in boxes(c):
                key = (col[0], col[1], col[2], col[3])
                if key not in pidx:
                    pidx[key] = len(palette) + 1
                    palette.append(key)
                lo = (x0 * factor - 0.5, y0 * factor - 0.5, z0 * factor - 0.5)
                hi = ((x1 + 1) * factor - 0.5, (y1 + 1) * factor - 0.5, (z1 + 1) * factor - 0.5)
                a, b = rig(lo), rig(hi)
                rlo = tuple(min(a[k], b[k]) for k in range(3))
                rhi = tuple(max(a[k], b[k]) for k in range(3))
                bx.append((rlo, rhi, pidx[key]))
            nparts += len(bx)
            if name == 'body':
                back = max(y for (x, y, z) in cells) + 0.5
        out_pieces.append({
            'name': name,
            'parent': par if par != root else None,
            'pivot': rig(info[name]['pivot']),
            'boxes': bx,
        })
    # the body's pivot height in the GLB, so its top is the rider's seat
    body_y = info['body']['pivot'][1]
    f = lambda x: ('%.2f' % x).rstrip('0').rstrip('.') if x != int(x) else str(int(x))
    lines = [
        '-- Generated by tools/mounts/export.py from ' + fname + ' (do not edit by hand).',
        '-- ' + look + ': ' + str(nparts) + ' parts at ' + str(factor) + ' GLB voxel(s) to a brick.',
        '-- Units are GLB voxels, rig-oriented (facing -Z); pivots in the parent piece\'s space.',
        'return {',
        '\tback = ' + f(body_y + back) + ', -- the top of the body over the ground: the rider\'s seat',
        '\tpalette = {',
    ]
    for (r, g, b, glow) in palette:
        lines.append('\t\t{ %d, %d, %d%s },' % (r, g, b, ', true' if glow else ''))
    lines.append('\t},')
    lines.append('\tpieces = {')
    for p in out_pieces:
        pv = p['pivot']
        lines.append('\t\t{ name = "%s", parent = %s, pivot = { %s, %s, %s }, boxes = {' % (
            p['name'], ('"%s"' % p['parent']) if p['parent'] else 'nil', f(pv[0]), f(pv[1]), f(pv[2])))
        row = []
        for (lo, hi, c) in p['boxes']:
            row.append('{%s,%s,%s,%s,%s,%s,%d}' % (f(lo[0]), f(lo[1]), f(lo[2]), f(hi[0]), f(hi[1]), f(hi[2]), c))
        for i in range(0, len(row), 8):
            lines.append('\t\t\t' + ','.join(row[i:i + 8]) + ',')
        lines.append('\t\t} },')
    lines.append('\t},')
    lines.append('}')
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, look + '.luau'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    return nparts


if __name__ == '__main__':
    factor = int(sys.argv[1]) if len(sys.argv) > 1 else 2
    for look, fname in FILES.items():
        print(look, export(look, fname, factor), 'parts')
